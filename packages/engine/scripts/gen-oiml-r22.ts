/**
 * Generates data/oiml-r22/table-20c.json from data/oiml-r22/coefficients.json.
 * rho20(p) = A1 + sum_{k=2..12} A_k p^(k-1)   (OIML R 22 (1975) p.4-5, p.12-13, t = 20 C so B/C terms vanish)
 * %v/v = %w/w * rho20(p) / rho20(100%)         (OIML R 22 p.5, table IIIb)
 * Run: node --experimental-strip-types scripts/gen-oiml-r22.ts   (or tsx)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { Decimal as BaseDecimal } from 'decimal.js';

const D = BaseDecimal.clone({ precision: 34, rounding: BaseDecimal.ROUND_HALF_EVEN });
const coeffs = JSON.parse(
  readFileSync(new URL('../data/oiml-r22/coefficients.json', import.meta.url), 'utf8'),
) as { A: string[] | null };

if (!coeffs.A || coeffs.A.length !== 12) {
  console.error('gen-oiml-r22: coefficients.json has no A_k.');
  process.exit(1);
}
const A = coeffs.A.map((s) => new D(s));

/** Horner evaluation of A1 + A2 p + ... + A12 p^11 with p as a decimal fraction. */
function rho20(p: BaseDecimal): BaseDecimal {
  let acc = new D(0);
  for (let k = A.length - 1; k >= 0; k--) acc = acc.times(p).plus(A[k]!);
  return acc;
}

const rhoEthanol = rho20(new D(1));
const DP = 10; // stored decimal places
const rows: { pctVV: string; pctWW: string; densityKgM3: string }[] = [];
for (let i = 0; i <= 1000; i++) {
  const ww = new D(i).div(10); // percent, exact
  const rho = rho20(ww.div(100));
  const vv = ww.times(rho).div(rhoEthanol);
  rows.push({
    pctVV: vv.toDecimalPlaces(DP).toFixed(DP),
    pctWW: ww.toFixed(1),
    densityKgM3: rho.toDecimalPlaces(DP).toFixed(DP),
  });
}

const out = {
  status: 'generated_from_official_formula',
  source: 'OIML R 22 (1975), https://www.oiml.org/en/files/pdf_r/r022-e75.pdf',
  retrievedOn: '2026-11-21',
  confidence: 'L3_standard',
  temperatureC: 20,
  ethanolDensity20CKgM3: rhoEthanol.toDecimalPlaces(DP).toFixed(DP),
  note: 'Generated by scripts/gen-oiml-r22.ts; do not edit by hand. Rows every 0.1 %w/w.',
  rows,
};
writeFileSync(new URL('../data/oiml-r22/table-20c.json', import.meta.url), JSON.stringify(out, null, 1) + '\n');
console.log('rows', rows.length, 'rho_ethanol_20C', out.ethanolDensity20CKgM3);
